"""Writes src/unicode_tables.rs: the character classes Python's str
methods and `re` use, from the Python that records the reference
(reference/generate.sh), so the crate classifies text as 1.x does on
that Python and not as the Rust standard library's Unicode version
would.

Run: python3 crates/fros-sensor/gen_unicode_tables.py
"""

import sys
import unicodedata
from pathlib import Path


def ranges(pred):
    out, start = [], None
    for c in range(0x110000):
        hit = pred(chr(c))
        if hit and start is None:
            start = c
        elif not hit and start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, doc, rows):
    lines = [f"/// {doc}", f"pub(crate) const {name}: &[(u32, u32)] = &["]
    lines += [f"    (0x{a:04X}, 0x{b:04X})," for a, b in rows]
    lines.append("];")
    return "\n".join(lines)


out = [
    "//! Generated by gen_unicode_tables.py from Python "
    f"{sys.version_info.major}.{sys.version_info.minor} (Unicode {unicodedata.unidata_version}); do not edit.",
    "",
    table("DECIMAL", "`str.isdecimal()`, which is what `re`'s `\\d` matches (category Nd).", ranges(str.isdecimal)),
    "",
    table("NOT_PRINTABLE", "Characters `str.isprintable()` refuses, which `repr` escapes.",
          ranges(lambda ch: not ch.isprintable())),
    "",
]
Path(__file__).with_name("src").joinpath("unicode_tables.rs").write_text("\n".join(out))
