func TestExpiryLikePython(t *testing.T) {
	defer func(l *time.Location) { Local = l }(Local)
	Local = time.UTC
	for _, c := range expiryCases {
		got := "ERR"
		if n, err := Expiry(c.in, c.tz, "expires"); err == nil {
			got = strconv.FormatInt(n, 10)
		}
		if got != c.want {
			t.Errorf("expires %q in %q = %s, 1.x %s", c.in, c.tz, got, c.want)
		}
	}
}
