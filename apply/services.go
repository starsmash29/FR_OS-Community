// --- DHCP (frfw.kea) ------------------------------------------------------------

// checkKea is `kea-dhcp4 -t` of text, from a throwaway file (Kea's
// tester takes no standard input), touching no running daemon.
func (s *System) checkKea(text string) error {
	f, err := os.CreateTemp("", "tmp*.json")
	if err != nil {
		return pyOSError(err)
	}
	path := f.Name()
	defer os.Remove(path)
	_, err = f.WriteString(text)
	if cerr := f.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		return pyOSError(err)
	}
	res, err := s.Run(Cmd{Argv: []string{"kea-dhcp4", "-t", path}})
	if errors.Is(err, ErrNotFound) {
		return stepErr("'kea-dhcp4' binary not found; install kea-dhcp4-server")
	}
	if err != nil {
		return err
	}
	if res.Code != 0 {
		if msg := config.PyStrip(res.Stderr); msg != "" {
			return &StepError{msg}
		}
		if msg := config.PyStrip(res.Stdout); msg != "" {
			return &StepError{msg}
		}
		return stepErr("kea-dhcp4 -t exited with status %d", res.Code)
	}
	return nil
}

// preflightKea checks the Kea config listening only on the devices that
// are there now: Kea's check refuses a device that doesn't exist, and a
// VLAN device is only created by this apply's address step. The DHCP
// step checks again with every device, once they exist.
func (s *System) preflightKea(c *config.Config) error {
	var failed error
	text, err := render.KeaListening(c, func(device string) bool {
		ok, err := s.DeviceExists(device)
		if err != nil && failed == nil {
			failed = err
		}
		return ok
	})
	if failed != nil {
		return failed
	}
	if err != nil {
		return err
	}
	return s.checkKea(text)
}

// syncKea checks and, unless dryRun, writes and loads the DHCPv4 config.
func (s *System) syncKea(c *config.Config, dryRun bool) (string, error) {
	if c.Dhcp.Zones.Len() == 0 {
		return "No DHCP zones configured", nil
	}
	text, err := render.Kea(c)
	if err != nil {
		return "", err
	}
	if err := s.checkKea(text); err != nil {
		return "", err
	}
	if dryRun {
		return "Kea config syntax OK (dry-run, not applied)", nil
	}
	if !s.root() {
		return "", stepErr("Applying the DHCP config requires root privileges.")
	}
	path := s.Paths.KeaConfig
	if err := mkdirParent(path); err != nil {
		return "", pyOSError(err)
	}
	if err := writeText(path, text); err != nil {
		return "", pyOSError(err)
	}
	res, err := Systemctl(s.Run, "restart", KeaService, 0)
	if errors.Is(err, ErrNotFound) {
		return "", stepErr("'systemctl' not found")
	}
	if err != nil {
		return "", err
	}
	if res.Code != 0 {
		if msg := config.PyStrip(res.Stderr); msg != "" {
			return "", &StepError{msg}
		}
		return "", stepErr("failed to restart %s", KeaService)
	}
	return "Kea DHCP config applied (" + path + ")", nil
}

// --- the ad-block DNS resolver (frfw.adblock.dns_service) -------------------------

// hostsFileHeader heads every hosts file FR_OS writes.
const hostsFileHeader = "# Managed by FR_OS (frfw.adblock) -- regenerated by `firewall-cli\n" +
	"# adblock-refresh`, do not edit by hand. One deduped entry per\n" +
	"# blocked domain, hosts-format (\"0.0.0.0 <domain>\"), served by the\n" +
	"# fr-adblock-dns dnsmasq instance via addn-hosts= (see\n" +
	"# frfw.adblock.dns_service).\n"

// ignoredHostnames are the entries every stock hosts file carries for
// reasons unrelated to ad-blocking.
var ignoredHostnames = map[string]bool{
	"localhost": true, "localhost.localdomain": true, "local": true, "broadcasthost": true,
	"ip6-localhost": true, "ip6-loopback": true, "ip6-localnet": true, "ip6-mcastprefix": true,
	"ip6-allnodes": true, "ip6-allrouters": true, "ip6-allhosts": true,
}

// blocklistHostname is frfw.adblock's _HOSTNAME_RE: dot-separated labels
// of 1-63 ASCII letters, digits and hyphens, none starting or ending
// with a hyphen.
func blocklistHostname(s string) bool {
	if s == "" {
		return false
	}
	for _, label := range strings.Split(s, ".") {
		if len(label) < 1 || len(label) > 63 || label[0] == '-' || label[len(label)-1] == '-' {
			return false
		}
		for i := 0; i < len(label); i++ {
			c := label[i]
			if !(c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' || c == '-') {
				return false
			}
		}
	}
	return true
}

// parseHostsText is a blocklist's text as its unique, lowercased domains:
// hosts format ("<ip> <name> ...") or one name per line.
func parseHostsText(text string) map[string]bool {
	domains := map[string]bool{}
	for _, line := range config.PySplitlines(text) {
		line, _, _ = strings.Cut(line, "#")
		line = config.PyStrip(line)
		if line == "" {
			continue
		}
		tokens := config.PySplit(line)
		if len(tokens) == 1 {
			h := strings.TrimRight(config.PyLower(tokens[0]), ".")
			if strings.Contains(h, ".") && !ignoredHostnames[h] && blocklistHostname(h) {
				domains[h] = true
			}
			continue
		}
		if _, _, err := config.IPAddress(tokens[0]); err != nil {
			continue
		}
		for _, h := range tokens[1:] {
			h = config.PyLower(h)
			if !ignoredHostnames[h] && blocklistHostname(h) {
				domains[h] = true
			}
		}
	}
	return domains
}

func readHostsFile(path string) (map[string]bool, error) {
	text, err := readFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return map[string]bool{}, nil
	}
	if err != nil {
		return nil, pyOSError(err)
	}
	return parseHostsText(text), nil
}

func writeHostsFile(domains map[string]bool, path string) error {
	if err := mkdirParent(path); err != nil {
		return pyOSError(err)
	}
	var b strings.Builder
	b.WriteString(hostsFileHeader)
	for _, d := range slices.Sorted(mapKeys(domains)) {
		b.WriteString("0.0.0.0 " + d + "\n")
	}
	return pyOSError(writeText(path, b.String()))
}

func mapKeys(m map[string]bool) func(func(string) bool) {
	return func(yield func(string) bool) {
		for k := range m {
			if !yield(k) {
				return
			}
		}
	}
}

func allowlisted(domain string, allowlist []string) bool {
	for _, a := range allowlist {
		if domain == a || strings.HasSuffix(domain, "."+a) {
			return true
		}
	}
	return false
}

// countBlockedDomains is the lines of a hosts file that aren't blank or
// comments; 0 for none.
func countBlockedDomains(path string) (int, error) {
	text, err := readFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return 0, nil
	}
	if err != nil {
		return 0, pyOSError(err)
	}
	n := 0
	for _, line := range config.PySplitlines(text) {
		if config.PyStrip(line) != "" && !strings.HasPrefix(line, "#") {
			n++
		}
	}
	return n, nil
}

// neverBlocked are adblocker.allowlist and every local_dns name: no
// blocklist may hold them.
func neverBlocked(c *config.Config) []string {
	names := slices.Clone(c.Adblocker.Allowlist)
	ld := c.LocalDNS
	local := append(slices.Clone(ld.Hosts.Keys), ld.Overrides.Keys...)
	if ld.Domain != "" {
		local = append(local, ld.Domain)
	}
	allow := c.Adblocker.Allowlist
	for _, n := range local {
		if !slices.Contains(allow, n) { // only against the allowlist, as 1.x's comprehension
			names = append(names, n)
		}
	}
	return names
}

func categoryPath(dir, name string) string { return filepath.Join(dir, name+".hosts") }

// enforceAllowlist takes the allowlisted and local names out of the
// lists already downloaded, so an allowlist edit takes effect on the
// next apply without a refresh. It returns how many entries went.
func (s *System) enforceAllowlist(c *config.Config) (int, error) {
	allow := append(neverBlocked(c), render.FirefoxDoHCanary)
	files := []string{s.Paths.AdblockHosts}
	for _, n := range c.Adblocker.Categories.Keys {
		files = append(files, categoryPath(s.Paths.AdblockCategoryDir, n))
	}
	removed := 0
	for _, path := range files {
		domains, err := readHostsFile(path)
		if err != nil {
			return 0, err
		}
		kept := map[string]bool{}
		for d := range domains {
			if !allowlisted(d, allow) {
				kept[d] = true
			}
		}
		if len(kept) != len(domains) {
			removed += len(domains) - len(kept)
			if err := writeHostsFile(kept, path); err != nil {
				return 0, err
			}
		}
	}
	return removed, nil
}

// ensureHostsPlaceholder: dnsmasq's addn-hosts= fails the whole config
// for a file that isn't there, so enabling the feature before the first
// refresh gets an empty list. Never overwrites a list.
func ensureHostsPlaceholder(path string) error {
	if exists(path) {
		return nil
	}
	if err := mkdirParent(path); err != nil {
		return pyOSError(err)
	}
	return pyOSError(writeText(path, "# (empty -- run `firewall-cli adblock-refresh` to populate)\n"))
}

func (s *System) dnsmasqPaths() render.DnsmasqPaths {
	return render.DnsmasqPaths{Hosts: s.Paths.AdblockHosts, CategoryDir: s.Paths.AdblockCategoryDir,
		QueryLog: s.Paths.DNSQueryLog}
}

// testDnsmasq is `dnsmasq --test` of a config file, running nothing.
func (s *System) testDnsmasq(path string) error {
	res, err := s.Run(Cmd{Argv: []string{"dnsmasq", "--test", "--conf-file=" + path}})
	if errors.Is(err, ErrNotFound) {
		return stepErr("'dnsmasq' binary not found; install dnsmasq")
	}
	if err != nil {
		return err
	}
	if res.Code != 0 {
		if msg := config.PyStrip(res.Stderr); msg != "" {
			return &StepError{msg}
		}
		if msg := config.PyStrip(res.Stdout); msg != "" {
			return &StepError{msg}
		}
		return stepErr("dnsmasq --test failed")
	}
	return nil
}

// preflightDnsmasq checks the resolver's config from a throwaway
// directory.
func (s *System) preflightDnsmasq(c *config.Config) error {
	text := render.Dnsmasq(c, s.dnsmasqPaths(), s.Catalog)
	dir, err := os.MkdirTemp("", "tmp")
	if err != nil {
		return pyOSError(err)
	}
	defer os.RemoveAll(dir)
	conf := filepath.Join(dir, "dnsmasq.conf")
	if err := writeText(conf, text); err != nil {
		return pyOSError(err)
	}
	return s.testDnsmasq(conf)
}

// resolverActive is `systemctl is-active` of the resolver, run directly.
func (s *System) resolverActive() bool {
	res, err := s.Run(Cmd{Argv: []string{"systemctl", "is-active", "--", AdblockDNSService}})
	return err == nil && config.PyStrip(res.Stdout) == "active"
}

func (s *System) dnsSystemctl(action, failed string) error {
	res, err := Systemctl(s.Run, action, AdblockDNSService, 0)
	if errors.Is(err, ErrNotFound) {
		return stepErr("'systemctl' not found")
	}
	if err != nil {
		return err
	}
	if res.Code != 0 {
		if msg := config.PyStrip(res.Stderr); msg != "" {
			return &StepError{msg}
		}
		return stepErr("failed to %s %s", failed, AdblockDNSService)
	}
	return nil
}

// syncResolver reconciles the dedicated dnsmasq instance with
// config.adblocker. It never fetches anything: it serves what the last
// refresh downloaded.
func (s *System) syncResolver(c *config.Config, dryRun bool) (string, error) {
	p := s.Paths
	if !c.Adblocker.Enabled {
		if !exists(p.AdblockDnsmasqConf) && !s.resolverActive() {
			return "Ad-block DNS resolver disabled", nil
		}
		if dryRun {
			return "Would stop the ad-block DNS resolver (dry-run)", nil
		}
		if !s.root() {
			return "", stepErr("Applying the ad-block DNS resolver requires root privileges.")
		}
		if err := s.dnsSystemctl("stop", "stop"); err != nil {
			return "", err
		}
		if err := unlinkMissingOK(p.AdblockDnsmasqConf); err != nil {
			return "", pyOSError(err)
		}
		return "Ad-block DNS resolver disabled", nil
	}
	if dryRun {
		n, err := countBlockedDomains(p.AdblockHosts)
		if err != nil {
			return "", err
		}
		return "Would (re)start the ad-block DNS resolver (" + strconv.Itoa(n) + " domains currently loaded, dry-run)", nil
	}
	if !s.root() {
		return "", stepErr("Applying the ad-block DNS resolver requires root privileges.")
	}
	if err := ensureHostsPlaceholder(p.AdblockHosts); err != nil {
		return "", err
	}
	categories := c.Adblocker.Categories.Keys
	for _, n := range categories {
		if err := ensureHostsPlaceholder(categoryPath(p.AdblockCategoryDir, n)); err != nil {
			return "", err
		}
	}
	removed, err := s.enforceAllowlist(c)
	if err != nil {
		return "", err
	}
	text := render.Dnsmasq(c, s.dnsmasqPaths(), s.Catalog)
	if err := mkdirParent(p.AdblockDnsmasqConf); err != nil {
		return "", pyOSError(err)
	}
	if err := writeText(p.AdblockDnsmasqConf, text); err != nil {
		return "", pyOSError(err)
	}
	if err := s.testDnsmasq(p.AdblockDnsmasqConf); err != nil {
		return "", err
	}
	if err := s.dnsSystemctl("restart", "restart"); err != nil {
		return "", err
	}
	total, err := countBlockedDomains(p.AdblockHosts)
	if err != nil {
		return "", err
	}
	for _, n := range categories {
		k, err := countBlockedDomains(categoryPath(p.AdblockCategoryDir, n))
		if err != nil {
			return "", err
		}
		total += k
	}
	message := "Ad-block DNS resolver active, " + strconv.Itoa(total) + " domains loaded"
	if len(categories) > 0 {
		message += " (" + strconv.Itoa(len(categories)) + " categories)"
	}
	if removed > 0 {
		message += ", " + strconv.Itoa(removed) + " allowlisted entries removed"
	}
	if c.AppControl.Enabled && len(c.AppControl.BlockedApps) > 0 {
		message += ", " + strconv.Itoa(len(c.AppControl.BlockedApps)) + " app(s) blocked"
	}
	return message, nil
}

// --- the XDP SNI filter (frfw.xdp) ------------------------------------------------

// criticalDomains are up to limit domains of the downloaded blocklist,
// sorted, short enough for the kernel filter.
func criticalDomains(path string, limit int64) ([]string, error) {
	if limit <= 0 {
		return nil, nil
	}
	text, err := readFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, pyOSError(err)
	}
	var domains []string
	for _, line := range config.PySplitlines(text) {
		if config.PyStrip(line) == "" || strings.HasPrefix(line, "#") {
			continue
		}
		parts := config.PySplit(line)
		if len(parts) < 2 {
			continue
		}
		if len([]rune(parts[1])) < MaxSNILen {
			domains = append(domains, parts[1])
		}
	}
	slices.Sort(domains)
	if int64(len(domains)) > limit {
		domains = domains[:limit]
	}
	return domains, nil
}

// sampleNames is up to five names for a message, and how many weren't
// shown.
func sampleNames(names []string) string {
	ordered := slices.Sorted(slices.Values(names))
	var shown []string
	for i, n := range ordered {
		if i == 5 {
			break
		}
		shown = append(shown, config.Repr(n))
	}
	text := strings.Join(shown, ", ")
	if len(ordered) > 5 {
		text += ", ... (" + strconv.Itoa(len(ordered)-5) + " more not shown)"
	}
	return text
}
